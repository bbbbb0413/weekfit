    private final int width;
    private final int height;
    private final String landmarks;

    AvatarModel(int width, int height, String landmarks) {
        this.width = width;
        this.height = height;
        this.landmarks = landmarks;
    }

    public int width() { return width; }
    public int height() { return height; }
    public String landmarks() { return landmarks; }

    public static AvatarModel from(String value) {
        if (value == null || value.isBlank()) {
            return MANNEQUIN;
        }
        try {
            return valueOf(value.trim().toUpperCase(Locale.ROOT));
        } catch (IllegalArgumentException e) {
            throw new IllegalArgumentException("model 은 mannequin, wave, hip, cross, modi 중 하나입니다.");
        }
    }
